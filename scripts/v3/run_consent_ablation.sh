#!/usr/bin/env bash
# YR-254 — 상호 동의 절제. 수락 정책의 **학습된 거절**만 없애면 얼마나 달라지나.
#
# ■ 무엇을 재나
#   논문이 새로움으로 내세우는 것은 *제안과 수락을 갈라 두고 양쪽이 동의해야 확정* 이다.
#   지금까지 잰 것은 **장치가 돌아갔다**(한쪽 동의 확정 0건)뿐이고, **동의가 이득인가**는
#   한 번도 재지 않았다. 팔 `RL_NOVETO` 가 그 자리를 잰다 — 망은 그대로, 값 판단으로
#   거절하던 부분만 끈다. **용량 거절은 그대로 남으므로** 물리적으로 불가능한 거래는
#   여전히 막힌다.
#
# ■ 왜 진단 대역인가
#   판정 대역 9,400,000 은 [[YR-233]] 에서 **이미 썼고** `USED_BANDS` 가 막는다.
#   한 대역은 한 번만 쓴다. 이건 절제 실험이라 진단 대역이 제자리다 — 여기서 무엇이
#   참인지 알아내고, 논문 주장으로 쓸 값이면 그때 새 판정 대역에서 확증한다.
#
# ■ 왜 세 환경 전부인가
#   [[YR-286]] 이 보인 것: 혼잡 빈도가 바뀌면 결론이 바뀐다. 한 환경만 재면 그 함정에
#   그대로 빠진다. 셋을 **동시에** 돌리면 벽시계는 가장 느린 하나(혼잡)와 같으므로
#   **시간을 더 쓰지 않고 세 배로 안다.**
#
# ■ 짝이 맞는가
#   시드·부하 일정이 [[YR-286]] 과 **글자 그대로 같다**. 그래서 기준선(`NO_REALLOC`)은
#   `outputs/v3/env-*/` 것을 그대로 쓴다 — 다시 굴리지 않는다.
#   `RL` 은 여기서 다시 굴린다. 같은 값이 나오면 **결정성 확인**이 덤으로 붙는다.
set -u

ROOT="/mnt/c/Users/geonu/orca/workspaces/port_reinforcement/강화학습-판매"
PY="$HOME/.venvs/yard-rl/bin/python"
SEED=9900980
CKPT="outputs/v3/month-02/ckpt_029.pt"

QUIET="3500,3500,5000,7500,3500,5000,3500,5000,3500,7500,3500,5000,3500,5000,7500,12500,15000,3500,5000,3500,7500,3500,5000,3500,5000,3500,7500,5000,3500,3500"
MIXED="3500,3500,5000,7500,12500,15000,3500,5000,7500,3500,5000,7500,3500,5000,7500,12500,15000,3500,5000,7500,3500,5000,7500,3500,12500,15000,5000,7500,3500,3500"
HEAVY="3500,12500,15000,5000,7500,3500,12500,15000,5000,7500,12500,15000,3500,5000,7500,12500,15000,3500,12500,15000,5000,7500,12500,15000,3500,5000,7500,12500,15000,3500"

cd "$ROOT" || exit 1

run_env () {
  local key="$1" loads="$2"
  mkdir -p "outputs/v3/veto-$key"
  PYTHONPATH=src "$PY" -m yard_rl.v3.eval --seed "$SEED" --ckpt "$CKPT" --arms RL_NOVETO --loads "$loads" --workers 2 --out "outputs/v3/veto-$key" > "outputs/v3/veto-$key/run.log" 2>&1
  echo "[$key] 끝 (exit $?)"
}

echo "■ 상호 동의 절제 — 세 환경 동시 · 팔 2 × 환경 3 = 6 프로세스"
run_env quiet "$QUIET" &
run_env mixed "$MIXED" &
run_env heavy "$HEAVY" &
wait
echo "■ 셋 다 완료"
for k in quiet mixed heavy; do
  echo "--- $k ---"
  tail -3 "outputs/v3/veto-$k/run.log" 2>/dev/null
done
